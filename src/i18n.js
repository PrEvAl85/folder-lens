const SAVED_KEY = "fl.lang";

function pluralForm(n, lang) {
  if (lang === "ru") {
    const m10 = n % 10;
    const m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return "one";
    if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return "few";
    return "many";
  }
  if (lang === "zh" || lang === "ja" || lang === "ko") return "other";
  return n === 1 ? "one" : "other";
}

function detectLang() {
  const saved = localStorage.getItem(SAVED_KEY);
  if (saved && MESSAGES[saved]) return saved;
  const base = (navigator.language || "en").split("-")[0].toLowerCase();
  return MESSAGES[base] ? base : "en";
}

function interpolate(str, vars) {
  return str.replace(/\{(\w+)\}/g, (m, k) =>
    k in vars ? String(vars[k]) : m,
  );
}

const I18N = {
  lang: detectLang(),
  supported: Object.keys(MESSAGES),
  names: LANG_NAMES,
  t(key, vars = {}) {
    let msg = MESSAGES[this.lang];
    for (const part of key.split(".")) {
      if (msg == null) return key;
      msg = msg[part];
    }
    if (msg == null) return key;
    if (typeof msg === "object") {
      const form = pluralForm(vars.n ?? 0, this.lang);
      return interpolate(msg[form] ?? msg.other ?? "", vars);
    }
    return interpolate(msg, vars);
  },
  locale() {
    return LANG_LOCALES[this.lang];
  },
  set(lang) {
    if (!MESSAGES[lang]) return;
    this.lang = lang;
    localStorage.setItem(SAVED_KEY, lang);
  },
  apply() {
    for (const el of document.querySelectorAll("[data-i18n]")) {
      el.textContent = this.t(el.dataset.i18n);
    }
    for (const el of document.querySelectorAll("[data-i18n-placeholder]")) {
      el.placeholder = this.t(el.dataset.i18nPlaceholder);
    }
    for (const el of document.querySelectorAll("[data-i18n-title]")) {
      el.title = this.t(el.dataset.i18nTitle);
    }
    document.documentElement.lang = this.lang;
    document.title = this.t("app_title");
    const sel = document.getElementById("lang-select");
    if (sel) sel.value = this.lang;
  },
};

export default I18N;
